  /**
   * Strips all Unicode emojis, pictographs, symbols, and variation selectors from notification text.
   * @param {string} text
   * @returns {string}
   */
  function stripEmojis(text) {
    if (!text || typeof text !== 'string') return '';
    return text
      .replace(/[\u{1F600}-\u{1F64F}\u{1F300}-\u{1F5FF}\u{1F680}-\u{1F6FF}\u{1F700}-\u{1F77F}\u{1F780}-\u{1F7FF}\u{1F800}-\u{1F8FF}\u{1F900}-\u{1F9FF}\u{1FA00}-\u{1FA6F}\u{1FA70}-\u{1FAFF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}\u{2300}-\u{23FF}\u{2B50}\u{FE0F}\u{200D}]+/gu, '')
      .trim();
  }

  /**
   * Decodes HTML entities commonly generated by contenteditable divs and rich-text editors.
   * @param {string} str
   * @returns {string}
   */
  function decodeHtmlEntities(str) {
    if (!str || typeof str !== 'string') return '';
    return str
      .replace(/&nbsp;/gi, ' ')
      .replace(/&amp;/gi, '&')
      .replace(/&quot;/gi, '"')
      .replace(/&#39;|&apos;/gi, "'")
      .replace(/&lt;/gi, '<')
      .replace(/&gt;/gi, '>')
      .replace(/&#(\d+);/g, function (_, dec) {
        return String.fromCharCode(dec);
      });
  }

  /**
   * Sanitizes any string into a valid Firebase Cloud Messaging topic name.
   * Format allowed by Google FCM: [a-zA-Z0-9-_.~%]+
   * @param {string} input
   * @returns {string}
   */
  function sanitizeTopicName(input) {
    if (!input || typeof input !== 'string') return 'general';
    var sanitized = input
      .toLowerCase()
      .trim()
      .replace(/[^a-zA-Z0-9-_~]/g, '_')
      .replace(/_{2,}/g, '_')
      .replace(/^_+|_+$/g, '');
    if (!sanitized) return 'general';
    return sanitized.length > 100 ? sanitized.slice(0, 100) : sanitized;
  }

  /**
   * Computes the personal user topic for targeted member notifications.
   * @param {string} identifier - Email, IC, or Member ID
   * @returns {string} e.g. "user_jeshuakoh2008_gmail_com" or "user_080116140615"
   */
  function getUserTopic(identifier) {
    if (!identifier) return '';
    return 'user_' + sanitizeTopicName(identifier);
  }

  /**
   * Computes the department topic for team notifications.
   * @param {string} department
   * @returns {string} e.g. "dept_logistics"
   */
  function getDepartmentTopic(department) {
    if (!department) return '';
    return 'dept_' + sanitizeTopicName(department);
  }

  /**
   * Strips HTML tags, unescapes HTML entities, strips emojis, and collapses whitespace.
   * @param {string} html
   * @param {number} maxLen
   * @returns {string}
   */
  function cleanSnippet(html, maxLen) {
    maxLen = maxLen || 120;
    if (!html || typeof html !== 'string') return '';
    var text = stripEmojis(decodeHtmlEntities(html))
      .replace(/<[^>]+>/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
    if (text.length > maxLen) {
      return text.slice(0, maxLen - 3) + '...';
    }
    return text;
  }

  /**
   * Resolves complete member names and supported groups from text or rich content.
   * @param {string} text
   * @param {Array<Object>} [memberDirectory]
   * @returns {{ targetUsers: Array<string>, topics: Array<string> }}
   */
  function resolveMentionTargets(text, memberDirectory) {
    if (typeof text !== 'string' || !text.includes('@')) return { targetUsers: [], topics: [] };
    var targetUsers = new Set();
    var topics = new Set();
    var cached = (typeof _cachedDepartmentMembers !== 'undefined') ? _cachedDepartmentMembers : [];
    var directory = getMentionDirectoryMembers(Array.isArray(memberDirectory) ? memberDirectory : cached);
    var membersByMention = new Map();
    directory.forEach(function(member) {
      [member.name, member.email, member.ic].map(normalizeMentionName).filter(Boolean).forEach(function(name) {
        if (!membersByMention.has(name)) membersByMention.set(name, member.name.trim());
      });
    });
    var groupTopics = {
      all: 'announcements', everyone: 'announcements', everybody: 'announcements',
      secretariat: 'dept_secretariat', logistics: 'dept_logistics', media: 'dept_media', hq: 'dept_hq',
      officer: 'dept_officers', officers: 'dept_officers', nco: 'dept_nco', ncos: 'dept_nco'
    };
    var matcher = createMentionMatcher(Object.keys(groupTopics).concat(Array.from(membersByMention.keys())));
    var plainText = decodeHtmlEntities(text.replace(/<[^>]+>/g, ' '));
    for (var match of plainText.matchAll(matcher)) {
      var mention = normalizeMentionName(match[2]);
      if (Object.hasOwn(groupTopics, mention)) topics.add(groupTopics[mention]);
      if (membersByMention.has(mention)) targetUsers.add(membersByMention.get(mention));
    }

    return {
      targetUsers: Array.from(targetUsers),
      topics: Array.from(topics)
    };
  }

  /**
   * Converts a PKCS#8 PEM string to an ArrayBuffer for WebCrypto.
   * @param {string} pem
   * @returns {ArrayBuffer}
   */
  function pemToArrayBuffer(pem) {
    var b64 = pem
      .replace(/-----BEGIN PRIVATE KEY-----/, '')
      .replace(/-----END PRIVATE KEY-----/, '')
      .replace(/[\r\n\s]+/g, '');
    var binary = atob(b64);
    var bytes = new Uint8Array(binary.length);
    for (var i = 0; i < binary.length; i++) {
      bytes[i] = binary.charCodeAt(i);
    }
    return bytes.buffer;
  }

  /**
   * Base64URL encoder (RFC 4648 §5).
   * @param {Uint8Array|ArrayBuffer|string} input
   * @returns {string}
   */
  function base64UrlEncode(input) {
    var str = '';
    if (typeof input === 'string') {
      var utf8Bytes = new TextEncoder().encode(input);
      for (var i = 0; i < utf8Bytes.length; i++) {
        str += String.fromCharCode(utf8Bytes[i]);
      }
    } else {
      var uint8 = input instanceof Uint8Array ? input : new Uint8Array(input);
      for (var j = 0; j < uint8.length; j++) {
        str += String.fromCharCode(uint8[j]);
      }
    }
    return btoa(str)
      .replace(/=/g, '')
      .replace(/\+/g, '-')
      .replace(/\//g, '_');
  }

